typedef std::vector<unsigned char> Bytes;

std::string g_root;  // scratch directory, absolute

void PutU32LE( Bytes& b, unsigned long v )
{
    b.push_back( (unsigned char)( v & 0xff ) );
    b.push_back( (unsigned char)( ( v >> 8 ) & 0xff ) );
    b.push_back( (unsigned char)( ( v >> 16 ) & 0xff ) );
    b.push_back( (unsigned char)( ( v >> 24 ) & 0xff ) );
}
void PutName( Bytes& b, const char* p4 )
{
    for ( int i = 0; i < 4; i++ ) b.push_back( (unsigned char)p4[i] );
}

// A minimal but REAL .rif: RIFF <form> [ LIST FVER [ DATA <short ver> ] ]
// [ LIST <form> [ DATA <marker string> ] ]. The marker is how a check tells
// which copy of an entry the loader actually returned.
Bytes MakeRif( const char* pForm, int iVer, const std::string& sMarker )
{
    Bytes inner;
    PutName( inner, "DATA" );
    PutU32LE( inner, 2 );
    inner.push_back( (unsigned char)( iVer & 0xff ) );
    inner.push_back( (unsigned char)( ( iVer >> 8 ) & 0xff ) );

    Bytes fver;
    PutName( fver, "LIST" );
    PutU32LE( fver, (unsigned long)( 4 + inner.size( ) ) );
    PutName( fver, "FVER" );
    fver.insert( fver.end( ), inner.begin( ), inner.end( ) );

    Bytes mark;
    PutName( mark, "DATA" );
    PutU32LE( mark, (unsigned long)sMarker.size( ) );
    mark.insert( mark.end( ), sMarker.begin( ), sMarker.end( ) );
    if ( sMarker.size( ) & 1 ) mark.push_back( 0 );

    Bytes body;
    PutName( body, "LIST" );
    PutU32LE( body, (unsigned long)( 4 + mark.size( ) ) );
    PutName( body, pForm );
    body.insert( body.end( ), mark.begin( ), mark.end( ) );

    Bytes out;
    PutName( out, "RIFF" );
    PutU32LE( out, (unsigned long)( 4 + fver.size( ) + body.size( ) ) );
    PutName( out, pForm );
    out.insert( out.end( ), fver.begin( ), fver.end( ) );
    out.insert( out.end( ), body.begin( ), body.end( ) );
    return out;
}

void MakeDirs( const std::string& sPath )
{
    std::string s;
    for ( size_t i = 0; i < sPath.size( ); i++ )
    {
        s += sPath[i];
        if ( sPath[i] == '\\' || sPath[i] == '/' ) _mkdir( s.c_str( ) );
    }
    _mkdir( sPath.c_str( ) );
}

void WriteFile( const std::string& sPath, const Bytes& b )
{
    size_t slash = sPath.find_last_of( "\\/" );
    if ( slash != std::string::npos ) MakeDirs( sPath.substr( 0, slash ) );
    FILE* fp = NULL;
    fopen_s( &fp, sPath.c_str( ), "wb" );
    if ( fp == NULL ) return;
    if ( !b.empty( ) ) fwrite( &b[0], 1, b.size( ), fp );
    fclose( fp );
}
void WriteText( const std::string& sPath, const std::string& s )
{
    Bytes b( s.begin( ), s.end( ) );
    WriteFile( sPath, b );
}
void Unlink( const std::string& sPath ) { _unlink( sPath.c_str( ) ); }

bool LoggedOpen( const char* pSubstr )
{
    for ( size_t i = 0; i < g_openLog.size( ); i++ )
        if ( g_openLog[i].find( pSubstr ) != std::string::npos ) return true;
    return false;
}
bool LoggedExact( const std::string& s )
{
    for ( size_t i = 0; i < g_openLog.size( ); i++ )
        if ( g_openLog[i] == s ) return true;
    return false;
}
bool MmioOpened( const std::string& s )
{
    for ( size_t i = 0; i < g_mmioLog.size( ); i++ )
        if ( g_mmioLog[i] == s ) return true;
    return false;
}
void ResetLogs( )
{
    g_openLog.clear( );
    g_mmioLog.clear( );
    g_msgBoxes.clear( );
}

