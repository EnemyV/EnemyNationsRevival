//---------------------------------------------------------------------------
//  A synthetic WSDF container: magic, table size, then (len,name,offset)* and
//  the entry payloads concatenated in table order.
//---------------------------------------------------------------------------

struct ContainerEntry
{
    std::string sName;
    Bytes       payload;
};

void WriteContainer( const std::string& sPath, const std::vector<ContainerEntry>& entries )
{
    LONG cbTable = 0;
    for ( size_t i = 0; i < entries.size( ); i++ )
        cbTable += (LONG)( 4 + entries[i].sName.size( ) + 1 + 4 );

    Bytes out;
    PutName( out, "WSDF" );
    PutU32LE( out, (unsigned long)cbTable );

    unsigned long off = (unsigned long)( 8 + cbTable );
    Bytes         table;
    for ( size_t i = 0; i < entries.size( ); i++ )
    {
        PutU32LE( table, (unsigned long)( entries[i].sName.size( ) + 1 ) );
        for ( size_t j = 0; j < entries[i].sName.size( ); j++ ) table.push_back( (unsigned char)entries[i].sName[j] );
        table.push_back( 0 );
        PutU32LE( table, off );
        off += (unsigned long)entries[i].payload.size( );
    }
    out.insert( out.end( ), table.begin( ), table.end( ) );
    for ( size_t i = 0; i < entries.size( ); i++ )
        out.insert( out.end( ), entries[i].payload.begin( ), entries[i].payload.end( ) );

    WriteFile( sPath, out );
}

std::vector<ContainerEntry> StockContainer( )
{
    std::vector<ContainerEntry> v;
    ContainerEntry              e1;
    e1.sName   = "units\\units.rif";
    e1.payload = MakeRif( "UNIT", kRifVer, "CONTAINER" );
    v.push_back( e1 );
    ContainerEntry e2;
    e2.sName = "files\\stdgta.dat";
    const char* pGta = "stdgta-bytes-0123456789";
    e2.payload.assign( (const unsigned char*)pGta, (const unsigned char*)pGta + strlen( pGta ) );
    v.push_back( e2 );
    ContainerEntry e3;
    e3.sName   = "research\\research.rif";
    e3.payload = MakeRif( "RSRH", kRifVer, "CONTAINER" );
    v.push_back( e3 );
    return v;
}

void TestContainerFallbackAndLoosePrecedence( )
{
    const std::string sDir = g_root + "\\Both";
    const std::string sDat = sDir + "\\ENations.dat";
    const std::string sData = sDir + "\\data";
    WriteContainer( sDat, StockContainer( ) );

    // No loose units.rif yet: the container must serve it.
    MakeDirs( sData );
    {
        CDataFile df;
        df._Init( sDat.c_str( ), sData.c_str( ), kRifVer );
        ResetLogs( );
        CMmio* p = df.OpenAsMMIO( "units", "UNIT" );
        CHECK( p != NULL );
        CHECK( MmioOpened( sDat ) );  // came out of the container
        delete p;
        df.Close( );
    }

    // Now add a VALID loose copy with a different marker: the loose copy wins.
    WriteFile( sData + "\\units\\units.rif", MakeRif( "UNIT", kRifVer, "LOOSE" ) );
    {
        CDataFile df;
        df._Init( sDat.c_str( ), sData.c_str( ), kRifVer );
        ResetLogs( );
        CMmio* p = df.OpenAsMMIO( "units", "UNIT" );
        CHECK( p != NULL );
        CHECK( MmioOpened( sData + "\\units\\units.rif" ) );
        CHECK( !MmioOpened( sDat ) );
        delete p;
        df.Close( );
    }

    // And a loose copy of the WRONG version falls through to the container
    // rather than failing (the designed fallback).
    WriteFile( sData + "\\units\\units.rif", MakeRif( "UNIT", kRifVer + 1, "STALE" ) );
    {
        CDataFile df;
        df._Init( sDat.c_str( ), sData.c_str( ), kRifVer );
        ResetLogs( );
        CMmio* p = df.OpenAsMMIO( "units", "UNIT" );
        CHECK( p != NULL );
        CHECK( MmioOpened( sDat ) );
        delete p;
        df.Close( );
    }
    Unlink( sData + "\\units\\units.rif" );
}

void TestGetContainerEntrySize( )
{
    const std::string sDir = g_root + "\\Sizes";
    const std::string sDat = sDir + "\\ENations.dat";
    const std::vector<ContainerEntry> v = StockContainer( );
    WriteContainer( sDat, v );

    CDataFile df;
    df._Init( sDat.c_str( ), NULL, kRifVer );

    DWORD dw = 0;
    CHECK( df.GetContainerEntrySize( "files\\stdgta.dat", dw ) );
    CHECK_EQ( dw, (DWORD)v[1].payload.size( ) );

    // First entry: bounded by the next offset, not by EOF.
    CHECK( df.GetContainerEntrySize( "units\\units.rif", dw ) );
    CHECK_EQ( dw, (DWORD)v[0].payload.size( ) );

    // Last entry: bounded by EOF.
    CHECK( df.GetContainerEntrySize( "research\\research.rif", dw ) );
    CHECK_EQ( dw, (DWORD)v[2].payload.size( ) );

    // Case-insensitive on the key, and unknown names say so.
    CHECK( df.GetContainerEntrySize( "FILES\\STDGTA.DAT", dw ) );
    CHECK_EQ( dw, (DWORD)v[1].payload.size( ) );
    CHECK( !df.GetContainerEntrySize( "no\\such.rif", dw ) );

    df.Close( );

    // With no container open there is nothing to measure.
    CDataFile dfLoose;
    dfLoose._Init( NULL, ( g_root + "\\Flat\\data" ).c_str( ), kRifVer );
    CHECK( !dfLoose.GetContainerEntrySize( "files\\stdgta.dat", dw ) );
    dfLoose.Close( );
}

