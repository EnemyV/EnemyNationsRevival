void TestPinWrittenOnlyForAContainerThatOpened( )
{
    // Phase 2's pin rule: Init writes Game\DataFile back only when a container
    // actually opened, so a loose-only run cannot pin a dead path.
    //
    // These run on the GLOBAL theDataFile on purpose: CDataFile::Init calls
    // theDataFile._Init( ) by name and then tests its OWN m_pDataFile, so the
    // guard is only meaningful on that one instance. (Pre-existing shape - the
    // game has exactly one CDataFile - but it makes Init untestable on any
    // other object, and the check would pass vacuously on a local one.)
    const std::string sDir  = g_root + "\\Pin";
    const std::string sData = sDir + "\\data";
    WriteText( sData + "\\manifest.txt", "units/units.rif 1 x\n" );
    WriteFile( sData + "\\units\\units.rif", MakeRif( "UNIT", kRifVer, "LOOSE" ) );
    WriteContainer( sDir + "\\real.dat", StockContainer( ) );

    char szCwd[MAX_PATH] = { 0 };
    ::GetCurrentDirectoryA( sizeof( szCwd ), szCwd );
    ::SetCurrentDirectoryA( sDir.c_str( ) );

    // Loose-only: the pinned path does not exist and there is no container
    // beside the exe either, so _Init falls into loose-only mode.
    w22::Profile( ).vals["Game\\DataFile"] = ( sDir + "\\dead.dat" );
    w22::Profile( ).vals["Game\\Patch"]    = "data";
    w22::Profile( ).writes                 = 0;

    CHECK( theDataFile.Init( "ENations.dat", kRifVer, FALSE ) );
    CHECK_EQ( w22::Profile( ).writes, 0 );
    CHECK( std::string( w22::GetProfileString( "Game", "DataFile", "" ) ) == ( sDir + "\\dead.dat" ) );
    theDataFile.Close( );

    // A real container: the pin IS written back, unchanged behaviour.
    w22::Profile( ).vals["Game\\DataFile"] = ( sDir + "\\real.dat" );
    w22::Profile( ).writes                 = 0;
    CHECK( theDataFile.Init( "ENations.dat", kRifVer, FALSE ) );
    CHECK_EQ( w22::Profile( ).writes, 1 );
    theDataFile.Close( );

    ::SetCurrentDirectoryA( szCwd );
}

//---------------------------------------------------------------------------
//  The hash pipeline on top of the loader: what bytes come back, and do a
//  loose install and a container install agree on them.
//---------------------------------------------------------------------------

Bytes ReadWholeFile( const std::string& sPath )
{
    Bytes b;
    FILE* fp = NULL;
    fopen_s( &fp, sPath.c_str( ), "rb" );
    if ( fp == NULL ) return b;
    unsigned char tmp[4096];
    size_t        n;
    while ( ( n = fread( tmp, 1, sizeof( tmp ), fp ) ) > 0 ) b.insert( b.end( ), tmp, tmp + n );
    fclose( fp );
    return b;
}

unsigned long HashOneRiff( CDataFile& df, const char* pEntry, const char* pForm, const char* const* ppNames,
                           int cNames )
{
    std::vector<unsigned char> buf;
    unsigned long              h = endatahash::kFnvOffset;
    const bool                 bOk = endataread::ReadRiffEntry( df, pEntry, pForm, buf );
    endatahash::HashSetMember( h, 0, ( bOk && !buf.empty( ) ) ? &buf[0] : NULL, bOk ? buf.size( ) : 0, ppNames,
                               cNames );
    return h;
}

